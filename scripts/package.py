#!/usr/bin/env python3
"""Pack this extension into the .c7s.zip layout the panel installs."""

import os
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = "dev_minerpl_caddyproxy"
OUT = ROOT / "dist" / f"{PACKAGE}.c7s.zip"

FILE_ATTR = 0o100644 << 16
DIR_ATTR = 0o040755 << 16
COMMENT = b"this .c7s.zip extension archive has been generated by calagopus extension export"


def add_dir(archive: zipfile.ZipFile, name: str) -> None:
    if not name.endswith("/"):
        name += "/"
    info = zipfile.ZipInfo(name)
    info.external_attr = DIR_ATTR
    info.compress_type = zipfile.ZIP_STORED
    archive.writestr(info, b"")


def add_file(archive: zipfile.ZipFile, arcname: str, path: Path) -> None:
    info = zipfile.ZipInfo(arcname)
    info.external_attr = FILE_ATTR
    info.compress_type = zipfile.ZIP_DEFLATED
    archive.writestr(info, path.read_bytes(), compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    if OUT.exists():
        OUT.unlink()

    dirs: set[str] = set()

    def ensure_dirs(archive: zipfile.ZipFile, arcname: str) -> None:
        acc = ""
        for part in arcname.split("/")[:-1]:
            acc = f"{acc}{part}/"
            if acc not in dirs:
                add_dir(archive, acc)
                dirs.add(acc)

    backend_files = ["Cargo.toml", ".gitignore", "README.md"]
    for dirpath, dirnames, filenames in os.walk(ROOT / "src"):
        dirnames.sort()
        filenames.sort()
        for name in filenames:
            if name.endswith(".rs"):
                backend_files.append((Path(dirpath) / name).relative_to(ROOT).as_posix())

    frontend_files: list[str] = []
    for dirpath, dirnames, filenames in os.walk(ROOT / "frontend"):
        dirnames[:] = [d for d in dirnames if d not in {"node_modules", ".git"}]
        dirnames.sort()
        filenames.sort()
        for name in filenames:
            if name == "tsconfig.json":
                continue
            frontend_files.append((Path(dirpath) / name).relative_to(ROOT).as_posix())

    migration_files: list[str] = []
    for dirpath, dirnames, filenames in os.walk(ROOT / "migrations"):
        dirnames.sort()
        filenames.sort()
        for name in filenames:
            migration_files.append((Path(dirpath) / name).relative_to(ROOT).as_posix())

    with zipfile.ZipFile(OUT, "w") as archive:
        archive.comment = COMMENT
        add_file(archive, "Metadata.toml", ROOT / "Metadata.toml")
        for rel in backend_files:
            arc = f"backend/{rel}"
            ensure_dirs(archive, arc)
            add_file(archive, arc, ROOT / rel)
        for rel in frontend_files:
            ensure_dirs(archive, rel)
            add_file(archive, rel, ROOT / rel)
        for rel in migration_files:
            ensure_dirs(archive, rel)
            add_file(archive, rel, ROOT / rel)

    with zipfile.ZipFile(OUT) as archive:
        names = set(archive.namelist())
        required = [
            "Metadata.toml",
            "backend/",
            "backend/Cargo.toml",
            "backend/src/",
            "backend/src/lib.rs",
            "frontend/",
            "frontend/package.json",
            "frontend/src/",
            "frontend/src/index.tsx",
            "migrations/",
        ]
        missing = [name for name in required if name not in names]
        if missing:
            print("package is missing:", ", ".join(missing), file=sys.stderr)
            return 1
        lib = archive.read("backend/src/lib.rs").decode()
        index = archive.read("frontend/src/index.tsx").decode()
        if "pub struct ExtensionStruct" not in lib or "export default " not in index:
            print("package is missing the extension entry points", file=sys.stderr)
            return 1

    print(OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
